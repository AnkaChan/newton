"""Run and analyze actual float32 shared-corner round trips for seeded shapes.

Experimental CPU/SciPy driver. Seeded augmentation is generated by the existing
helper, then quantized at the input boundary. Geometry, polar extraction,
sparse matrices, right-hand sides, Krylov vectors, solution iterates, and output
are float32. Float64 is used only for explicitly labeled post-solve analysis.
"""

import argparse
import hashlib
import json
import time
from dataclasses import asdict
from pathlib import Path

import numpy as np

from .cell_frames import CellFrames
from .data import VoxelGridData, generate_cuboid
from .multiscale import build_hierarchy, generate_multiscale
from .round_trip import build_measurement_operators

__all__ = ["Float32Decoder", "compute_frames_float32", "project_null_component", "run_batch"]

CELL_COUNTS = (10, 10, 40)
CELL_SIZE = 0.025
STRENGTH = 0.5
TOLERANCE = 1e-7


def _require_float32(value: np.ndarray, name: str) -> None:
    if value.dtype != np.float32:
        raise TypeError(f"{name} must be float32, received {value.dtype}")


def compute_frames_float32(rest: VoxelGridData, positions: np.ndarray) -> CellFrames:
    """Extract centers/F/R/U with float32 arithmetic and LAPACK SGESDD.

    Use the same opposite-face-centroid formula as compute_cell_frames.
    SciPy's float32 LAPACK driver is used explicitly because NumPy linalg.svd
    can internally dispatch to double precision for float32 input.
    """
    from scipy.linalg import svd
    from scipy.linalg.lapack import get_lapack_funcs

    _require_float32(positions, "positions")
    if positions.shape != rest.corner_rest_positions.shape or not np.isfinite(positions).all():
        raise ValueError("positions must be finite shared corners with the canonical shape")
    corners = positions[rest.cell_corner_indices]
    signs = (2 * np.indices((2, 2, 2)).reshape(3, -1).T - 1).astype(np.float32)
    deformation = np.einsum("nki,kj->nij", corners - corners[:, :1], signs) / np.float32(4 * rest.cell_size)
    driver = get_lapack_funcs("gesdd", (deformation,))
    if driver.typecode != "s":
        raise RuntimeError(f"Expected SGESDD, got {driver.typecode}gesdd")
    left, singular, right_t = svd(deformation, full_matrices=False, check_finite=False, lapack_driver="gesdd")
    for name, value in (("F", deformation), ("SVD left", left), ("SVD values", singular), ("SVD right", right_t)):
        _require_float32(value, name)
    determinants = np.einsum("ni,ni->n", deformation[:, :, 0], np.cross(deformation[:, :, 1], deformation[:, :, 2]))
    valid = (determinants > 0) & (singular[:, -1] > np.float32(1e-6) * np.maximum(np.float32(1), singular[:, 0]))
    frames = left @ right_t
    local_axes = frames.transpose(0, 2, 1) @ deformation
    frames[~valid] = 0
    local_axes[~valid] = 0
    return CellFrames(corners.mean(axis=1, dtype=np.float32), deformation, frames, local_axes, determinants, valid)


class Float32Decoder:
    """Reuse float32 topology operators and guard all LSQR matrix-vector calls.

    SciPy LSQR must receive an explicit float32 zero x0; its default solution
    allocation is float64. Every matvec/rmatvec input/output and returned x is
    checked. The actual x/u/v/w recurrence dtype is additionally trace-audited
    in the unit tests. SciPy's scalar norm/condition bookkeeping may use Python
    double scalars; there is no double-precision vector or linear solve.
    """

    def __init__(self, rest: VoxelGridData):
        from scipy import sparse
        from scipy.sparse.linalg import LinearOperator

        self.rest = rest
        self.rest_positions = rest.corner_rest_positions.astype(np.float32)
        self.fixed = np.flatnonzero(rest.corner_rest_positions[:, 2] == rest.corner_rest_positions[:, 2].min())
        self.free = np.ones(len(self.rest_positions), dtype=bool)
        self.free[self.fixed] = False
        gradient, centers = build_measurement_operators(rest)
        self.gradient = gradient.astype(np.float32)
        self.centers = centers.astype(np.float32)
        # Sparse true division promotes to float64 in SciPy; multiply the
        # stored float32 coefficients in place to preserve the solve dtype.
        scaled_centers = self.centers.copy()
        scaled_centers.data *= np.float32(1 / rest.cell_size)
        self.matrix = sparse.vstack((self.gradient, scaled_centers), format="csr", dtype=np.float32)
        self.free_matrix = self.matrix[:, self.free]
        self.fixed_matrix = self.matrix[:, self.fixed]
        self.transpose = self.free_matrix.T.tocsr()
        self.rest_measurement = self.matrix @ self.rest_positions
        self.matvec_calls = 0
        self.rmatvec_calls = 0

        def matvec(value):
            _require_float32(value, "LSQR matvec input")
            result = self.free_matrix @ value
            _require_float32(result, "LSQR matvec output")
            self.matvec_calls += 1
            return result

        def rmatvec(value):
            _require_float32(value, "LSQR rmatvec input")
            result = self.transpose @ value
            _require_float32(result, "LSQR rmatvec output")
            self.rmatvec_calls += 1
            return result

        self.operator = LinearOperator(self.free_matrix.shape, matvec=matvec, rmatvec=rmatvec, dtype=np.float32)

    def rhs(self, encoded: CellFrames, fixed_positions: np.ndarray) -> np.ndarray:
        """Build dimensionless gradient and centers/h residuals in float32."""
        for name, value in (
            ("R", encoded.frames),
            ("U", encoded.local_axes),
            ("centers", encoded.centers),
            ("fixed positions", fixed_positions),
        ):
            _require_float32(value, name)
        target = np.vstack(
            (
                (encoded.frames @ encoded.local_axes).transpose(0, 2, 1).reshape(-1, 3),
                encoded.centers / np.float32(self.rest.cell_size),
            )
        )
        result = (
            target - self.rest_measurement - self.fixed_matrix @ (fixed_positions - self.rest_positions[self.fixed])
        )
        _require_float32(result, "RHS")
        return result

    def decode(self, encoded: CellFrames, fixed_positions: np.ndarray, *, tolerance: float = TOLERANCE):
        """Run actual zero-start float32 LSQR for each world coordinate."""
        from scipy.sparse.linalg import lsqr

        if not encoded.valid.all():
            raise ValueError("Input has invalid float32 polar frames")
        right_hand_side = self.rhs(encoded, fixed_positions)
        displacement = np.zeros_like(self.rest_positions)
        displacement[self.fixed] = fixed_positions - self.rest_positions[self.fixed]
        diagnostics = []
        for axis in range(3):
            result = lsqr(
                self.operator,
                right_hand_side[:, axis],
                x0=np.zeros(self.free.sum(), dtype=np.float32),
                atol=tolerance,
                btol=tolerance,
                conlim=1e7,
                iter_lim=10000,
                damp=0.0,
            )
            _require_float32(result[0], "LSQR solution iterate")
            displacement[self.free, axis] = result[0]
            diagnostics.append(
                {
                    "world_axis": axis,
                    "stop_code": int(result[1]),
                    "iterations": int(result[2]),
                    "estimated_residual_norm": float(result[3]),
                    "condition_estimate": float(result[6]),
                }
            )
        positions = self.rest_positions + displacement
        positions[self.fixed] = fixed_positions
        _require_float32(positions, "reconstructed positions")
        return positions, displacement, right_hand_side, diagnostics


def project_null_component(rest: VoxelGridData, displacement: np.ndarray) -> np.ndarray:
    """Project onto alternating-xy layer modes in float64 for analysis only."""
    counts = tuple(count + 1 for count in rest.cell_counts)
    values = np.asarray(displacement, dtype=np.float64).reshape(*counts, 3)
    i, j = np.indices(counts[:2])
    signs = (-1.0) ** (i + j)
    coefficients = np.einsum("ij,ijkd->kd", signs, values) / (counts[0] * counts[1])
    coefficients[0] = 0
    return (signs[:, :, None, None] * coefficients[None, None]).reshape(-1, 3)


def _euclidean_rmse(values):
    return float(np.sqrt(np.mean(np.sum(np.asarray(values, dtype=np.float64) ** 2, axis=-1))))


def analyze_result(decoder, original, encoded, recovered, displacement, rhs):
    """Measure stored float32 states and equations with float64 accumulation."""
    original64, recovered64 = original.astype(np.float64), recovered.astype(np.float64)
    error = recovered64 - original64
    original_displacement = original64 - decoder.rest_positions.astype(np.float64)
    null_original = project_null_component(decoder.rest, original_displacement)
    null_error = project_null_component(decoder.rest, error)
    rowspace_error = error - null_error
    # Evaluate the exact matrix/RHS that LSQR received, without a float32
    # residual's final cancellation masking a solver error.
    equation = decoder.free_matrix.astype(np.float64) @ displacement[decoder.free].astype(np.float64) - rhs.astype(
        np.float64
    )
    normal_equation = decoder.free_matrix.astype(np.float64).T @ equation
    # These use the same stored single-precision coefficients and encoded
    # measurements; only this post-solve diagnostic accumulation is float64.
    measured_f = (decoder.gradient.astype(np.float64) @ recovered64).reshape(-1, 3, 3).transpose(0, 2, 1)
    target_f = (encoded.frames @ encoded.local_axes).astype(np.float64)
    f_error = measured_f - target_f
    center_error = decoder.centers.astype(np.float64) @ recovered64 - encoded.centers.astype(np.float64)
    rms = _euclidean_rmse(error)
    maximum = float(np.linalg.norm(error, axis=1).max())
    deformation_rms = _euclidean_rmse(original_displacement)
    length = max(decoder.rest.cell_counts) * decoder.rest.cell_size
    polar_error = target_f - encoded.deformation.astype(np.float64)
    return {
        "corner_rmse_m": rms,
        "corner_max_error_m": maximum,
        "corner_rmse_mm": 1000 * rms,
        "corner_max_error_mm": 1000 * maximum,
        "corner_rmse_pct_object_length": 100 * rms / length,
        "corner_max_pct_object_length": 100 * maximum / length,
        "corner_rmse_pct_cell_size": 100 * rms / decoder.rest.cell_size,
        "corner_max_pct_cell_size": 100 * maximum / decoder.rest.cell_size,
        "original_displacement_rmse_m": deformation_rms,
        "original_displacement_max_m": float(np.linalg.norm(original_displacement, axis=1).max()),
        "corner_rmse_pct_deformation_rms": 100 * rms / deformation_rms if deformation_rms > 0 else 0.0,
        "polar_F_max_abs_error": float(np.abs(polar_error).max()),
        "equation_component_rms": float(np.sqrt(np.mean(equation**2))),
        "equation_max_abs_error": float(np.abs(equation).max()),
        "normal_equation_component_rms": float(np.sqrt(np.mean(normal_equation**2))),
        "gradient_component_rmse": float(np.sqrt(np.mean(f_error**2))),
        "gradient_max_abs_error": float(np.abs(f_error).max()),
        "center_rmse_m": _euclidean_rmse(center_error),
        "center_max_error_m": float(np.linalg.norm(center_error, axis=1).max()),
        "boundary_max_error_m": float(np.linalg.norm(error[decoder.fixed], axis=1).max()),
        "null_predicted_corner_rmse_m": _euclidean_rmse(null_original),
        "null_error_rmse_m": _euclidean_rmse(null_error),
        "rowspace_error_rmse_m": _euclidean_rmse(rowspace_error),
        "null_unexplained_corner_rmse_m": _euclidean_rmse(error + null_original),
        "null_unexplained_corner_max_m": float(np.linalg.norm(error + null_original, axis=1).max()),
    }


def _atomic_json(path: Path, value: dict):
    temporary = path.with_suffix(".tmp")
    temporary.write_text(json.dumps(value, indent=2, allow_nan=False) + "\n")
    temporary.replace(path)


def _settings(rest, tolerance):
    import scipy

    return {
        "cell_counts": list(rest.cell_counts),
        "cell_size_m": rest.cell_size,
        "cell_count": len(rest.cell_corner_indices),
        "corner_count": len(rest.corner_rest_positions),
        "strength": STRENGTH,
        "max_levels": 3,
        "hierarchy": [asdict(level) for level in build_hierarchy(rest, strength=STRENGTH)],
        "pipeline_dtype": "float32",
        "analysis_dtype": "float64 (post-solve only)",
        "input_quantization": "Existing deterministic float64 augmentation quantized to float32 before encoding",
        "polar_svd": "SciPy LAPACK SGESDD (native float32)",
        "decoder": "Stored origins + polar R + local U + known material z-min face",
        "solver": "SciPy LSQR, explicit float32 zero x0, guarded float32 matvec/rmatvec and output",
        "scalar_bookkeeping": "SciPy may use Python double scalars for norm/condition/stop bookkeeping; Krylov vectors and x iterates remain float32",
        "solver_atol": tolerance,
        "solver_btol": tolerance,
        "solver_iter_limit": 10000,
        "solver_conlim": 1e7,
        "regularization": "none",
        "centers_row_weight": "1/h, equal dimensionless weight to F rows",
        "numpy_version": np.__version__,
        "scipy_version": scipy.__version__,
        "corner_rmse_definition": "RMS Euclidean xyz error across all shared corners",
        "equation_rms_definition": "sqrt(mean((A_free_float32*u_float32-b_float32)^2)) over 16000 rows and 3 coordinates; evaluated in float64 after solving",
        "null_diagnostic": "Offline float64 projection onto 40 alternating-xy layer modes per coordinate; never used in reconstruction",
    }


def run_batch(output: Path, *, seed_start=0, count=100, tolerance=TOLERANCE, resume=False):
    """Run actual float32 solves, persisting each seed before continuing."""
    rest = generate_cuboid(CELL_COUNTS, cell_size=CELL_SIZE)
    decoder = Float32Decoder(rest)
    output = Path(output)
    (output / "samples").mkdir(parents=True, exist_ok=True)
    (output / "states").mkdir(exist_ok=True)
    settings = _settings(rest, tolerance)
    settings["configuration_sha256"] = hashlib.sha256(json.dumps(settings, sort_keys=True).encode()).hexdigest()
    _atomic_json(output / "settings.json", settings)
    entries = []
    batch_start = time.perf_counter()
    for seed in range(seed_start, seed_start + count):
        name = f"seed_{seed:03d}"
        path = output / "samples" / f"{name}.json"
        if resume and path.exists():
            entry = json.loads(path.read_text())
            if entry.get("configuration_sha256") != settings["configuration_sha256"]:
                raise ValueError(f"Cannot resume seed {seed}: configuration differs")
            if entry.get("status") == "complete" and (output / "states" / f"{name}.npz").exists():
                entries.append(entry)
                continue
        start = time.perf_counter()
        entry = {"seed": seed, "configuration_sha256": settings["configuration_sha256"]}
        try:
            sample = generate_multiscale(rest, seed=seed, strength=STRENGTH)
            original = sample.positions.astype(np.float32)
            encoded = compute_frames_float32(rest, original)
            recovered, displacement, rhs, diagnostics = decoder.decode(
                encoded, original[decoder.fixed], tolerance=tolerance
            )
            metrics = analyze_result(decoder, original, encoded, recovered, displacement, rhs)
            converged = all(axis["stop_code"] in (0, 1, 2, 4, 5) for axis in diagnostics)
            entry.update(
                {
                    "status": "complete" if converged else "solver_not_converged",
                    "strength": STRENGTH,
                    "effective_scale": sample.effective_scale,
                    "backtracking_steps": sample.backtracking_steps,
                    "screen": sample.screen,
                    "min_center_det_float32": float(encoded.determinants.min()),
                    "hierarchy": [asdict(level) for level in sample.levels],
                    "metrics": metrics,
                    "solver": diagnostics,
                    "dtypes": {
                        "positions": str(original.dtype),
                        "F": str(encoded.deformation.dtype),
                        "R": str(encoded.frames.dtype),
                        "U": str(encoded.local_axes.dtype),
                        "matrix": str(decoder.matrix.dtype),
                        "rhs": str(rhs.dtype),
                        "displacement": str(displacement.dtype),
                        "output": str(recovered.dtype),
                    },
                    "archive": f"states/{name}.npz",
                }
            )
            np.savez_compressed(
                output / entry["archive"],
                original_positions=original,
                recovered_positions=recovered,
                displacement=displacement,
                stored_centers=encoded.centers,
                stored_R=encoded.frames,
                stored_U=encoded.local_axes,
                fixed_indices=decoder.fixed,
                seed=seed,
            )
        except Exception as error:
            entry.update({"status": "failed", "error": f"{type(error).__name__}: {error}"})
        entry["wall_seconds"] = time.perf_counter() - start
        _atomic_json(path, entry)
        entries.append(entry)
        if len(entries) % 10 == 0 or len(entries) == count:
            success = [item for item in entries if item["status"] == "complete"]
            print(
                json.dumps(
                    {
                        "processed": len(entries),
                        "complete": len(success),
                        "requested": count,
                        "rms_mm_min": min((item["metrics"]["corner_rmse_mm"] for item in success), default=None),
                        "rms_mm_max": max((item["metrics"]["corner_rmse_mm"] for item in success), default=None),
                        "elapsed_seconds": time.perf_counter() - batch_start,
                    }
                ),
                flush=True,
            )
    _atomic_json(
        output / "batch.json",
        {
            "settings": settings,
            "seed_start": seed_start,
            "count": count,
            "samples": entries,
            "wall_seconds": time.perf_counter() - batch_start,
            "dtype_guard_calls": {"matvec": decoder.matvec_calls, "rmatvec": decoder.rmatvec_calls},
        },
    )
    return entries


def _main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=Path(__file__).parent / "generated" / "round_trip_100")
    parser.add_argument("--seed-start", type=int, default=0)
    parser.add_argument("--count", type=int, default=100)
    parser.add_argument("--tolerance", type=float, default=TOLERANCE)
    parser.add_argument("--resume", action="store_true")
    args = parser.parse_args()
    if args.count < 1 or args.seed_start < 0 or not 0 < args.tolerance < 1:
        parser.error("count must be positive, seed-start nonnegative, and tolerance in (0,1)")
    run_batch(args.output, seed_start=args.seed_start, count=args.count, tolerance=args.tolerance, resume=args.resume)


if __name__ == "__main__":
    _main()
