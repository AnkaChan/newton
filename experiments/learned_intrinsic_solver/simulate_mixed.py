"""Roll out a trained mixed-pool checkpoint on held-out validation seeds.

Experimental. Each seed is regenerated by the validation augmenter exactly as
in training validation, then advanced with K learned optimizer iterations per
physical step for the requested duration using the same trajectory factory,
history plumbing and physical advance as the trainer. Trajectories are written
in the layout that ``render_learned`` and ``learned_simulation_gallery``
consume. Network weights are never modified; a failed trajectory keeps its last
valid frames and is reported instead of aborting the others.

Contact (``notes/contact-design-20260927.md``) follows the trainer: the seed's
static partners come from the trajectory factory, the frozen pairs of every
physical step are collated into the padded ``batch["contact"]`` layout that
``MixedHexSolverStep`` accepts, and the partners are saved with the trajectory
so ``render_learned`` can draw the floor and the static points.

The network and the step are rebuilt with the checkpoint's ``target_modes``
(schema 6). Each seed's gravity is the one its validation context sampled
(``metadata["gravity"]``, see ``MixedTrainConfig.gravity_magnitude_range``);
the report records it, falling back to the step's default when the metadata
carries none.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import math
import os
import time
from pathlib import Path

import numpy as np

__all__ = ["run_rollouts"]


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _atomic_json(path: Path, value: dict) -> None:
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text(json.dumps(value, indent=2, allow_nan=False) + "\n")
    temporary.replace(path)


def _atomic_npz(path: Path, **arrays) -> None:
    temporary = path.with_suffix(".tmp.npz")
    np.savez_compressed(temporary, **arrays)
    temporary.replace(path)


def _schedule(duration: float, dt: float, fps: int) -> tuple[int, int]:
    if not math.isfinite(duration) or duration <= 0:
        raise ValueError("duration must be finite and positive")
    if isinstance(fps, bool) or not isinstance(fps, int) or fps < 1:
        raise ValueError("fps must be a positive integer")
    steps = round(duration / dt)
    stride = round(1 / (dt * fps))
    if steps < 1 or stride < 1 or not math.isclose(steps * dt, duration, rel_tol=0, abs_tol=1e-9):
        raise ValueError("duration must contain whole physical steps and fps cannot exceed the step rate")
    if not math.isclose(stride * dt * fps, 1, rel_tol=0, abs_tol=1e-6):
        raise ValueError("fps must divide the physical step rate exactly")
    return steps, stride


class _Trajectory:
    """Frames, timing and status of one seed's rollout."""

    def __init__(self, seed: int, payload: dict, dt: float, *, default_gravity=(0.0, -9.81, 0.0)):
        from .contact_scene import ContactPartners  # noqa: PLC0415

        self.seed = seed
        self.payload = payload
        self.dt = dt
        self.gravity = [float(value) for value in payload["metadata"].get("gravity", default_gravity)]
        start = payload["physical_positions"].numpy().copy()
        self.frames = [start]
        self.times = [0.0]
        self.completed = 0
        self.calls = 0
        self.failure: dict | None = None
        self.material = dict(payload["context_spec"])
        self.perturbation_scale = float(payload["metadata"].get("perturbation_scale", float("nan")))
        self.min_center_jacobian = math.inf
        self.energies: list[float] = []
        partners = payload.get("contact_partners")
        self.contact = ContactPartners.from_dict(partners) if partners is not None else ContactPartners.contact_free()
        self.contact_metadata = dict(payload["metadata"].get("contact") or {})
        self.max_penetration_r = 0.0
        self.max_pair_count = 0

    @property
    def active(self) -> bool:
        return self.failure is None


def _contact_batch(payloads: list[dict], device) -> dict:
    """Collate the frozen contact pairs of ``payloads`` into the padded ``batch["contact"]`` layout.

    Mirrors the trainer's collation: ``sample_index`` and ``kind`` [B, Q] int64,
    ``partner_point`` and ``partner_normal`` [B, Q, 3] and ``partner_radius``
    [B, Q] float32, ``mask`` [B, Q] bool, with ``Q`` the largest pair count in
    the batch (zero when no payload has a pair).
    """
    import torch

    counts = [
        int(payload["contact_sample_index"].shape[0]) if "contact_sample_index" in payload else 0
        for payload in payloads
    ]
    width = max(counts, default=0)

    def pad(name, dtype, *tail):
        rows = []
        for payload, count in zip(payloads, counts, strict=True):
            padded = torch.zeros((width, *tail), dtype=dtype)
            if count:
                padded[:count] = payload[name].detach().to(dtype)
            rows.append(padded)
        return torch.stack(rows).to(device)

    return {
        "sample_index": pad("contact_sample_index", torch.int64),
        "kind": pad("contact_kind", torch.int64),
        "partner_point": pad("contact_partner_point", torch.float32, 3),
        "partner_normal": pad("contact_partner_normal", torch.float32, 3),
        "partner_radius": pad("contact_partner_radius", torch.float32),
        "mask": torch.stack([torch.arange(width) < count for count in counts]).to(device),
    }


def _run_query(step, trajectories, *, cell_count, device, train_mixed, history_module, features):
    """One learned iteration for every active trajectory; isolate failures per seed."""
    import torch

    active = [t for t in trajectories if t.active]
    if not active:
        return

    def attempt(group):
        payloads = [t.payload for t in group]
        batch = train_mixed._batch(payloads, device, cell_count=cell_count)
        # The trainer collates None for payloads without pair tensors; the step reads that as no contact.
        if batch.get("contact") is None:
            batch["contact"] = _contact_batch(payloads, device)
        result = train_mixed._checked_forward(step, step, batch)
        history_module.store_history(payloads, result)
        with torch.no_grad():
            deformation = features.center_deformation(result.positions, step.cell_corner_indices, step.center_gradients)
            jacobians = torch.linalg.det(deformation).min(dim=1).values.cpu().tolist()
            energies = result.loss.total.detach().cpu().tolist()
            pair_counts = batch["contact"]["mask"].sum(dim=1).cpu().tolist()
            penetration = result.contact_max_penetration
            penetrations = [0.0] * len(group) if penetration is None else penetration.detach().cpu().tolist()
        for index, trajectory in enumerate(group):
            trajectory.payload["candidate"] = result.positions[index].detach()
            trajectory.calls += 1
            trajectory.min_center_jacobian = min(trajectory.min_center_jacobian, float(jacobians[index]))
            trajectory.energies.append(float(energies[index]))
            trajectory.max_penetration_r = max(trajectory.max_penetration_r, float(penetrations[index]))
            trajectory.max_pair_count = max(trajectory.max_pair_count, int(pair_counts[index]))

    try:
        attempt(active)
    except (ValueError, RuntimeError, FloatingPointError):
        for trajectory in active:
            try:
                attempt([trajectory])
            except (ValueError, RuntimeError, FloatingPointError) as error:
                trajectory.failure = {
                    "physical_step": trajectory.completed + 1,
                    "last_valid_time_seconds": trajectory.completed * trajectory.dt,
                    "learned_calls_before_failure": trajectory.calls,
                    "error": f"{type(error).__name__}: {error}"[:500],
                }


def run_rollouts(
    checkpoint: Path,
    output_dir: Path,
    *,
    seeds: tuple[int, ...],
    iterations: int,
    duration: float = 10.0,
    fps: int = 30,
    device: str = "cuda",
    perturbed_candidates: bool = False,
) -> list[dict]:
    """Roll out ``seeds`` for ``duration`` seconds with ``iterations`` learned calls per step."""
    import torch

    from . import features, train_mixed  # noqa: PLC0415
    from . import history as history_module  # noqa: PLC0415
    from .data import generate_cuboid  # noqa: PLC0415
    from .mixed_physics import MixedHexSolverStep  # noqa: PLC0415
    from .network import IntrinsicSolverNetwork  # noqa: PLC0415

    checkpoint, output_dir = Path(checkpoint), Path(output_dir)
    if isinstance(iterations, bool) or not isinstance(iterations, int) or iterations < 1:
        raise ValueError("iterations must be a positive integer")
    seeds = tuple(int(seed) for seed in seeds)
    if not seeds or len(set(seeds)) != len(seeds) or any(seed < 0 for seed in seeds):
        raise ValueError("seeds must be unique nonnegative validation seeds")
    saved = torch.load(checkpoint, map_location="cpu", weights_only=False)
    if saved.get("format") != "mixed_pool_v2":
        raise ValueError("checkpoint is not a mixed_pool_v2 training checkpoint")
    config = train_mixed.MixedTrainConfig.from_checkpoint_config(saved["config"])
    if any(seed >= config.validation_count for seed in seeds):
        raise ValueError(f"validation seeds must be below validation_count={config.validation_count}")
    dt = config.time_step
    requested_steps, stride = _schedule(duration, dt, fps)
    target = torch.device(device)
    if target.type not in ("cpu", "cuda"):
        raise ValueError("device must be cpu or cuda")
    if target.type == "cuda":
        target = torch.device("cuda:0")
        torch.cuda.set_device(target)
        torch.cuda.reset_peak_memory_stats(target)
    output_dir.mkdir(parents=True, exist_ok=True)
    for seed in seeds:
        if (output_dir / f"seed_{seed}" / "trajectory.npz").exists():
            raise FileExistsError(f"rollout output already exists for seed {seed}")
    previous_threads = torch.get_num_threads()
    previous_tf32 = (torch.backends.cuda.matmul.allow_tf32, torch.backends.cudnn.allow_tf32)
    previous_probability = train_mixed.PERTURBED_CANDIDATE_PROBABILITY
    torch.set_num_threads(config.cpu_threads)
    torch.backends.cuda.matmul.allow_tf32 = False
    torch.backends.cudnn.allow_tf32 = False
    torch.set_float32_matmul_precision("highest")
    if not perturbed_candidates:
        train_mixed.PERTURBED_CANDIDATE_PROBABILITY = 0.0
    step = None
    started = time.perf_counter()
    try:
        rest = generate_cuboid(config.cell_counts, cell_size=config.cell_size)
        fixed = np.flatnonzero(rest.corner_rest_positions[:, 2] == rest.corner_rest_positions[:, 2].min())
        network = IntrinsicSolverNetwork(
            config.cell_counts,
            config.state_feature_dim,
            target_modes=config.target_modes,
            conditioning_dim=config.conditioning_dim,
            hidden_dim=config.hidden_dim,
            edge_hidden_dim=config.edge_hidden_dim,
            num_heads=config.num_heads,
            hops=config.hops,
            max_step_size=config.max_step_size,
            query_chunk_size=config.query_chunk_size,
            edge_network=getattr(config, "edge_network", False),
            checkpoint_chunks=getattr(config, "checkpoint_chunks", False),
            contact_tokens=getattr(config, "contact", False),
        ).to(target)
        network.load_state_dict(saved["network_state"])
        step = MixedHexSolverStep(
            rest,
            fixed,
            network=network,
            time_step=dt,
            gravity=config.gravity,
            energy_floor_scale=config.energy_floor_scale,
            contact_max_pairs=getattr(config, "contact_max_pairs", 4),
            contact_tokens_per_cell=getattr(config, "contact_tokens_per_cell", 24),
            contact_friction_epsilon=getattr(config, "contact_friction_epsilon", 1e-2),
            target_modes=config.target_modes,
        ).to(target)
        step.eval()
        parameter_digest = hashlib.sha256(
            b"".join(p.detach().cpu().numpy().tobytes() for p in network.parameters())
        ).hexdigest()
        factory = train_mixed._TrajectoryFactory(step, rest, config, rank=0, validation=True)
        cell_count = len(step.cell_corner_indices)
        trajectories = [_Trajectory(seed, factory.reset(seed), dt, default_gravity=step.gravity) for seed in seeds]
        rest_positions = rest.corner_rest_positions.astype(np.float32)
        with torch.no_grad(), torch.autocast(device_type=target.type, enabled=False):
            for step_number in range(1, requested_steps + 1):
                for _ in range(iterations):
                    _run_query(
                        step,
                        trajectories,
                        cell_count=cell_count,
                        device=target,
                        train_mixed=train_mixed,
                        history_module=history_module,
                        features=features,
                    )
                for trajectory in trajectories:
                    if not trajectory.active:
                        continue
                    try:
                        trajectory.payload = factory.advance(trajectory.payload)
                    except (ValueError, RuntimeError, FloatingPointError) as error:
                        trajectory.failure = {
                            "physical_step": step_number,
                            "last_valid_time_seconds": trajectory.completed * dt,
                            "learned_calls_before_failure": trajectory.calls,
                            "error": f"advance: {type(error).__name__}: {error}"[:500],
                        }
                        continue
                    trajectory.completed += 1
                    positions = trajectory.payload["physical_positions"].numpy()
                    if trajectory.completed % stride == 0 or trajectory.completed == requested_steps:
                        trajectory.frames.append(positions.copy())
                        trajectory.times.append(trajectory.completed * dt)
                if step_number % 100 == 0 or step_number == requested_steps:
                    alive = sum(t.active for t in trajectories)
                    elapsed = time.perf_counter() - started
                    print(
                        f"physical_step={step_number}/{requested_steps} active={alive}/{len(trajectories)} "
                        f"elapsed={elapsed:.0f}s",
                        flush=True,
                    )
                if not any(t.active for t in trajectories):
                    break
        after_digest = hashlib.sha256(
            b"".join(p.detach().cpu().numpy().tobytes() for p in network.parameters())
        ).hexdigest()
        if after_digest != parameter_digest:
            raise RuntimeError("rollout changed checkpoint parameters")
        reports = []
        checkpoint_hash = _sha256(checkpoint)
        for trajectory in trajectories:
            directory = output_dir / f"seed_{trajectory.seed}"
            directory.mkdir(parents=True, exist_ok=True)
            if trajectory.failure is not None and trajectory.times[-1] != trajectory.completed * dt:
                trajectory.frames.append(trajectory.payload["physical_positions"].numpy().copy())
                trajectory.times.append(trajectory.completed * dt)
            positions = np.stack(trajectory.frames).astype(np.float32)
            contact = trajectory.contact
            report = {
                "schema_version": 2,
                "seed": trajectory.seed,
                "status": "failed" if trajectory.failure else "complete",
                "failure": trajectory.failure,
                "checkpoint": str(checkpoint),
                "checkpoint_sha256": checkpoint_hash,
                "checkpoint_epoch": int(saved["report"]["completed_epochs"]),
                "best_selection": saved["report"].get("best_selection"),
                "time_step": dt,
                "optimizer_iterations_per_step": iterations,
                "candidate_mode": "perturbed_inertial_50_50" if perturbed_candidates else "inertial",
                "requested_duration_seconds": duration,
                "actual_duration_seconds": trajectory.completed * dt,
                "requested_physical_steps": requested_steps,
                "completed_physical_steps": trajectory.completed,
                "learned_calls": trajectory.calls,
                "frame_rate": fps,
                "saved_frame_count": len(trajectory.frames),
                "material": trajectory.material,
                "gravity": trajectory.gravity,
                "target_modes": step.target_modes,
                "perturbation_scale": trajectory.perturbation_scale,
                "min_center_jacobian": (
                    trajectory.min_center_jacobian if math.isfinite(trajectory.min_center_jacobian) else None
                ),
                "energy_first_joule": trajectory.energies[0] if trajectory.energies else None,
                "energy_last_joule": trajectory.energies[-1] if trajectory.energies else None,
                "energy_max_joule": max(trajectory.energies) if trajectory.energies else None,
                "contact": {
                    "plane_present": contact.plane_present,
                    "plane_height": float(contact.plane_point[1]),
                    "point_count": contact.point_count,
                    "ke": contact.ke,
                    "kd": contact.kd,
                    "mu": contact.mu,
                    "kappa": trajectory.contact_metadata.get("kappa"),
                    "beta": trajectory.contact_metadata.get("beta"),
                    "max_penetration_r": trajectory.max_penetration_r if trajectory.calls else None,
                    "max_pair_count": trajectory.max_pair_count,
                },
                "elapsed_seconds": time.perf_counter() - started,
                "gpu_peak_allocated_bytes": torch.cuda.max_memory_allocated(target) if target.type == "cuda" else 0,
                "working_dtype": "float32",
                "tf32_enabled": False,
            }
            _atomic_npz(
                directory / "trajectory.npz",
                positions=positions,
                times=np.asarray(trajectory.times, dtype=np.float64),
                rest_positions=rest_positions,
                fixed_indices=fixed.astype(np.int64),
                cell_counts=np.asarray(rest.cell_counts, dtype=np.int64),
                cell_corner_indices=rest.cell_corner_indices.astype(np.int64),
                contact_plane_present=np.asarray(contact.plane_present, dtype=bool),
                contact_plane_point=contact.plane_point.numpy().astype(np.float32),
                contact_plane_normal=contact.plane_normal.numpy().astype(np.float32),
                contact_point_positions=contact.point_positions.numpy().astype(np.float32),
                contact_point_normals=contact.point_normals.numpy().astype(np.float32),
                contact_point_radii=contact.point_radii.numpy().astype(np.float32),
            )
            _atomic_json(directory / "report.json", report)
            reports.append(report)
            factory.retire(trajectory.payload)
        _atomic_json(
            output_dir / ("rollouts_" + "-".join(str(seed) for seed in seeds) + ".json"),
            {
                "checkpoint": str(checkpoint),
                "checkpoint_sha256": checkpoint_hash,
                "seeds": list(seeds),
                "iterations": iterations,
                "duration_seconds": duration,
                "fps": fps,
                "completed": [r["seed"] for r in reports if r["status"] == "complete"],
                "failed": [r["seed"] for r in reports if r["status"] == "failed"],
                "elapsed_seconds": time.perf_counter() - started,
            },
        )
        return reports
    finally:
        train_mixed.PERTURBED_CANDIDATE_PROBABILITY = previous_probability
        torch.set_num_threads(previous_threads)
        torch.backends.cuda.matmul.allow_tf32, torch.backends.cudnn.allow_tf32 = previous_tf32
        if step is not None:
            step.close()


def _main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, allow_abbrev=False)
    parser.add_argument("--checkpoint", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--seeds", type=int, nargs="+", required=True)
    parser.add_argument("--iterations", type=int, default=8)
    parser.add_argument("--duration", type=float, default=10.0)
    parser.add_argument("--fps", type=int, default=30)
    parser.add_argument("--device", choices=("cpu", "cuda"), default="cuda")
    parser.add_argument("--perturbed-candidates", action="store_true")
    args = parser.parse_args()
    reports = run_rollouts(
        args.checkpoint,
        args.output_dir,
        seeds=tuple(args.seeds),
        iterations=args.iterations,
        duration=args.duration,
        fps=args.fps,
        device=args.device,
        perturbed_candidates=args.perturbed_candidates,
    )
    print(json.dumps({r["seed"]: r["status"] for r in reports}))
    if os.environ.get("LIDO_ROLLOUT_STRICT") and any(r["status"] != "complete" for r in reports):
        raise SystemExit(1)


if __name__ == "__main__":
    _main()
